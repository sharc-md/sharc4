# ----START of excitonic_slater_determinant class------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class excitonic_slater_determinant:
    def __init__(self, sites, site_states):
        self.excitations = set()
        self.site_states = {}  # list of electronic_state instances
        for idx, (state, site) in enumerate(zip(site_states, sites)):
            self.site_states[site] = state
            if site.aufbau_states[0] is not state:
                self.excitations.add((idx,state))
        self.level = len(self.excitations)
        self.Z = sum(self.site_states[site].Z for site in sites)
        self.M = sum(self.site_states[site].M for site in sites)
        self.index = None
        self.hash = self._hash()

    
    def _hash(self):
        h = hashlib.blake2b(digest_size=16)
        for st in self.site_states.values():
            h.update(struct.pack(">4q", st.Z, st.S, st.M, st.N))
        return int.from_bytes(h.digest(), "big")

    def __repr__(self):
        s = "[ "
        for site, state in self.site_states.items():
            if state.Z == 0:
                Z = "^(0)"
            elif state.Z > 0:
                Z = f"^({state.Z}+)"
            else:
                Z = f"^({abs(state.Z)}-)"
            s += f"{site.label}{Z} : {state.symbol(Z=False)} | "
        s = s[0 : len(s) - 3] + " ]"
        return s

    def __hash__(self):
        return self.hash
        #return repr(self).__hash__()

    def __eq__(self, other):
        return all(map(operator.is_, self.site_states.values(), other.site_states.values()))

    def __floordiv__(self, other):
        return all(map(operator.floordiv, self.site_states.values(), other.site_states.values()))

    # ----START of excitonic_slater_determinant.compare------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def compare(self, other):
        diffs = []

        for site, s1 in self.site_states.items():
            s2 = other.site_states[site]
            if s1 is not s2:
                diffs.append(site)
                if len(diffs) > 2:
                    return None

        nd = len(diffs)
        if nd == 1:
            return {"relationship": (0, 1), "exciton": diffs[0]}
        if nd == 2:
            return {"relationship": (0, 2), "excitons": (diffs[0], diffs[1])}

    # ----END of excitonic_slater_determinant.compare------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------


# ----END of excitonic_slater_determinant class------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------


# ----START of excitonic_configuration_state_function class------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class excitonic_configuration_state_function:
    def __init__(self, m, ESDs, U):
        self.index = None
        self.multiplicity = m
        self.ESDs = ESDs
        self.U = U
        ESD = self.ESDs[0]
        self.site_states = ESD.site_states
        self.eci_rank = sum(
            1 for site, state in self.site_states.items() if not any(state is astate for astate in site.aufbau_states)
        )

    def __repr__(self):
        s = "( "
        for site, state in self.site_states.items():
            #  if not state in site.aufbau_states or state.Z != site.Z:
            if not state // site.aufbau_states[0]:
                if state.Z == 0:
                    Z = "^(0)"
                elif state.Z > 0:
                    Z = f"^({state.Z}+)"
                else:
                    Z = f"^({abs(state.Z)}-)"
                s += f"{site.label}{Z} : {state.symbol(Z=False, M=False)} | "
        if s == "( ":
            s = "( 0 )"
        if s != "( 0 )":
            s = s[0 : len(s) - 3] + " )"
        return s

    def __hash__(self):
        return self.__repr__().hash()


