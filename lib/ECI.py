    # ----START of ECI.calculate_Fmat------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def calculate_Fmat(self, nucs, mol):
        """
        F[pq] = sum_k Z_k * <p| 1/|r-R_k| |q>
        """
        coords_list = []
        charges_list = []
        for g in nucs:
            charges = g.mol.atom_charges() - g.Q
            coords  = g.mol.atom_coords()
            for Z, R in zip(charges, coords):
                if Z != 0:
                    charges_list.append(float(Z))
                    coords_list.append(R)

        coords_all  = np.asarray(coords_list, dtype=float)
        charges_all = np.asarray(charges_list, dtype=float)

        # (npts, nao, nao)
        j3c = mol.intor("int1e_grids", hermi=1, grids=coords_all)

        return np.einsum("kpq,k->pq", j3c, charges_all)

    # ----END of ECI.calculate_Fmat------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.calculate_Gtensor------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def calculate_Gtensor(self, moles):
        starts = {}
        ends = {}
        supermolecule = None
        for mol in moles:
            if not mol in starts.keys():
                starts[mol] = sum(m.nbas for m in starts.keys())
                ends[mol] = starts[mol] + mol.nbas
                if supermolecule is None:
                    supermolecule = mol.copy()
                else:
                    supermolecule = merge_moles(supermolecule, mol)

        G = supermolecule.intor(
            "int2e",
            shls_slice=(
                starts[moles[0]],
                ends[moles[0]],
                starts[moles[1]],
                ends[moles[1]],
                starts[moles[2]],
                ends[moles[2]],
                starts[moles[3]],
                ends[moles[3]],
            ),
        )
        return G

    # ----END of ECI.calculate_Gtensor------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    @staticmethod
    def extract_subbasis_from_global_indices(mole_basis, atoms, global_indices):
        subbasis = {}
        current_global_index = 0  # To track the global shell index

        for atom in atoms:
            filtered_shells = []
            shells = mole_basis[atom]
            # Iterate over local shells for this atom
            for shell in shells:
                # Check if the current global index is in the list of global indices to keep
                if current_global_index in global_indices:
                    filtered_shells.append(shell)
                # Increment the global index after each shell
                current_global_index += 1
            # If we found any shells for this atom, add them to the subbasis
            if filtered_shells:
                subbasis[atom] = filtered_shells
        return subbasis

    @staticmethod
    def ao2shell(mol, ao_index):
        # Loop over the ao_loc array to find the corresponding shell index
        for shell_index in range(len(mol.ao_loc) - 1):
            if mol.ao_loc[shell_index] <= ao_index < mol.ao_loc[shell_index + 1]:
                return shell_index
        # If it's the last shell
        if ao_index >= mol.ao_loc[-1]:
            return len(mol.ao_loc) - 1

