# ----START of ECI class--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class ECI:
    def __init__(self, job, sites, log):
        # Input
        self.job = job
        self.sites = sites
        self.log = log

        d = {m: None for m in self.job.multiplicities}

        # Intermediate
        self.ECIbasis = d.copy()
        self.H = d.copy()
        self.J = d.copy()
        self.K = d.copy()
        self.S = d.copy()
        self.V1 = d.copy()
        self.J1 = d.copy()
        self.K1 = d.copy()
        self.P = {}

        # Output
        self.E = d.copy()
        self.Psi = {"ECSF": d.copy(), "ESD": d.copy()}
        self.dignostics = d.copy()
        self.PR = d.copy()
        self.mu = d.copy()
        self.soc = d.copy()
        self.grad = d.copy()
        self.nacs = d.copy()

        return

    # ----START of ECI.run------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def run(self):
        self.configure()  # Sets number of CPUs, transforms ECI_level and CT_level so that fragment instances are in sets/lists, etc.
        t1 = time.time()
        self.construct_excitonic_basis()  # Building ECI-CT basis
        t2 = time.time()
        self.log.print(f"       Time spent in constructing the ECI basis (sec) = {round(t2 - t1, 3)}")
        self.allocate()
        t1 = time.time()
        self.calculate_Hmat()  # Construct entire ECI-CT Hamiltonian for all multiplicities
        t2 = time.time()
        self.log.print(f"       Time spent in calculating ECI Hamiltonian (sec) = {round(t2 - t1, 3)}")
        self.calculate_eigenstates()  # Diagonalize Hamiltonian matrix for each multiplicity
        self.calculate_properties()  # Calculate all properties requested by master
        self.print_states()
        return

    # ----END of ECI.run------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.configure------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def configure(self):
        sites = self.sites
        job = self.job

        # Sets num of cores for numpy and pyscf
        threadpool_limits(limits=job.ncpu)

        job.mem *= 1024**3

        for site in sites:
            aufbau_states = []
            for states in site.states.values():
                for s in states:
                    if s in site.aufbau_states:
                        aufbau_states.append(s)
            site.aufbau_states = aufbau_states.copy()

        # Transforms the entries in eci_level and ...
        eci_level = {}
        for rank, value in job.eci_level.items():
            if rank == 0:
                eci_level[0] = value
            else:
                eci_level[rank] = []
                for subset in value:
                    newsubset = {site for site in sites if site.label in subset}
                    eci_level[rank].append(newsubset)
        job.eci_level = eci_level

        # Transform active_integrals
        for JK in ["J", "K"]:
            for int_type in [(0, 0), (0, 1), (0, 2)]:
                newlist = []
                for multiple in job.active_integrals[JK][int_type]:
                    newtuple = []
                    for label in multiple:
                        newtuple.append([site for site in sites if site.label == label][0])
                    newtuple = tuple(newtuple)
                    newlist.append(newtuple)
                job.active_integrals[JK][int_type] = newlist

        self.log.print("    BASIC INFOS OF THE CALCULATION:")
        self.log.print("")
        self.log.print(f"       The number of CPUs for NumPY and PySCF set up to {job.ncpu}")
        self.log.print(f"       Multiplicities to be calculated: {job.multiplicities}")
        self.log.print("       ECI level:")
        eci_dict = {0: "GS", 1: "LE", 2: "DLE", 3: "TLE", 4: "QLE"}
        for i in range(5, len(sites) + 1):
            eci_dict[i] = str(i) + "LE"
        for level, value in job.eci_level.items():
            self.log.print(f"       {eci_dict[level]:>5}: {value}")

        self.log.print("")
        self.log.print("    BASIC INFOS OF THE SITES:")
        for f in sites:
            self.log.print("")
            self.log.print(f"       Site: {f.label}")
            self.log.print("")
            self.log.print(
                "                  Atoms:       " + "".join([f"{f.mol.atom_pure_symbol(i):10}" for i in range(f.mol.natm)])
            )
            self.log.print("           RESP charges: " + "".join([f"{f.Q[i]: 10.5f}" for i in range(f.mol.natm)]))
            self.log.print("")
            S = f.mol.intor("int1e_ovlp")
            states = [s for ss in f.states.values() for s in ss]
            energies = [f.H[s.Z][f.states[s.Z].index(s), f.states[s.Z].index(s)].astype(float) for s in states]
            nel = [np.einsum("ij,ij->", S, f.rho[s.Z][(s, s, "tot")]) for s in states]
            nela = [np.einsum("ij,ij->", S, f.rho[s.Z][(s, s, "aa")]) for s in states]
            nelb = [np.einsum("ij,ij->", S, f.rho[s.Z][(s, s, "bb")]) for s in states]
            w1 = max(len(s.symbol()) for s in states)
            w2 = max(len(f"{e:.8f}") for e in energies)
            w3 = max(len(f"{n:.8f}") for n in nel)
            w4 = max(len(f"{n:.8f}") for n in nela)
            w5 = max(len(f"{n:.8f}") for n in nelb)
            width = max([w1, w2, w3, w4, w5]) + 2
            self.log.print("            Site states: " + "".join([f"{s.symbol():>{width}}" for s in states]))
            self.log.print("          Site energies: " + "".join([f"{e:>{width}.8f}" for e in energies]))
            self.log.print("            Num. of el.: " + "".join([f"{n:>{width}.8f}" for n in nel]))
            self.log.print("                  Alpha: " + "".join([f"{n:>{width}.8f}" for n in nela]))
            self.log.print("                   Beta: " + "".join([f"{n:>{width}.8f}" for n in nelb]))

    # ----END of ECI.configure------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.construct_excitonic_basis------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def construct_excitonic_basis(self):
        self.log.print("")
        self.log.print("    CONSTRUCTION OF THE ECI BASIS:")
        self.log.print("")
        allESDs = self.get_aufbaus()
        allESDs = self.make_excitations(allESDs)
        allESDs = self.overlap_criterion(allESDs)
        for m in self.job.multiplicities:
            ESDs, ECSFs, U = self.spin_adapt(m, allESDs)
            self.ECIbasis[m] = excitonic_basis(ESDs, ECSFs, U)
        return

    # ----END of ECI.construct_excitonic_basis------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.get_aufbaus------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def get_aufbaus(self):
        job = self.job
        sites = self.sites

        aufbaus = []
        aufbaustates = [site.aufbau_states for site in sites]
        aufbaus = itertools.product(*aufbaustates)
        ESDs = [excitonic_slater_determinant(sites=sites, site_states=list(aufbau)) for aufbau in aufbaus]

        # Take only those with correct charge
        ESDs = [ESD for ESD in ESDs if ESD.Z == job.charge]
        if len(ESDs) == 0:
            raise ValueError(
                "       No aufbau ESD has the requested charge "
                + str(job.charge)
                + "! Either change the given set of aufbau site states or do not calculate this full-system charge. Aborting..."
            )

        self.log.info(f"       Aufbau ESDs ( # = {len(ESDs)} )")
        return ESDs

    # ----END of ECI.get_aufbaus------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.make_excitations------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def make_excitations(self, ESDs):
        job = self.job
        sites = self.sites
        excitedESDs = set()
        for aufbau in ESDs:
            site_states_map = aufbau.site_states
            for level, subsets in job.eci_level.items():
                if level > 0:
                    for subset in subsets:
                        aufbau_state_sets = {f: set(f.aufbau_states) for f in subset}
                        site_state_lists = (
                            (s for s in f.states[site_states_map[f].Z] if s not in aufbau_state_sets[f]) for f in subset
                        )
                        subset_index = {f: i for i, f in enumerate(subset)}
                        default_site_states = [site_states_map[f] for f in sites]
                        for e in itertools.product(*site_state_lists):
                            site_states = list(default_site_states)
                            for f in subset:
                                i = sites.index(f)
                                site_states[i] = e[subset_index[f]]
                            excitedESDs.add(excitonic_slater_determinant(sites=sites, site_states=site_states))
        if job.eci_level.get(0, False):
            ESDs = ESDs.union(excitedESDs)
        else:
            ESDs = excitedESDs
        self.log.print(f"       Number of aufbau and excited ESDs before overlap criterion: {len(ESDs)}")
        self.log.print("")
        return ESDs

    # ----END of ECI.make_excitations------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.overlap_criterion------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def overlap_criterion(self, ESDs):
        self.log.print("       Overlap criterion:")
        self.log.print("")
        job = self.job

        # Get site-state pairs that overlap too much
        pairs_to_expell = {}

        active_pairs = set()
        for JK in ["J", "K"]:
            for int_type in [(0, 0), (0, 1), (0, 2)]:
                active_pairs.update(job.active_integrals[JK][int_type])

        for f1, f2 in active_pairs:
            pairs_to_expell[(f1, f2)] = []
            dimer = merge_moles(f1.mol, f2.mol)
            if (
                dist := np.min(
                    np.linalg.norm(
                        f1.mol.atom_coords(unit="Ang")[:, np.newaxis, :] - f2.mol.atom_coords(unit="Ang")[np.newaxis, :, :],
                        axis=-1,
                    )
                )
            ) > 1:
                self.log.print(f"          Pair {f1.label}, {f2.label} skipped. Minimal distance {dist:.3f} A.")
                continue
            SAO = dimer.intor("int1e_ovlp")[0 : f1.mol.nao :, f1.mol.nao :]

            for Z1, states1 in f1.states.items():
                for Z2, states2 in f2.states.items():
                    self.log.print(f"          (Fragment,charge) pair: ({f1.label},{Z1}), ({f2.label},{Z2}):")
                    S = {}
                    for s1 in states1:
                        rho1a = f1.rho[s1.Z][(s1, s1, "aa")]
                        rho1b = f1.rho[s1.Z][(s1, s1, "bb")]
                        for s2 in states2:
                            rho2a = f2.rho[s2.Z][(s2, s2, "aa")]
                            rho2b = f2.rho[s2.Z][(s2, s2, "bb")]
                            S[(s1, s2)] = np.einsum(
                                "ij,kl,il,jk", rho1a, rho2a, SAO, SAO, optimize=["einsum_path", (0, 2), (0, 1), (0, 1)]
                            )
                            S[(s1, s2)] += np.einsum(
                                "ij,kl,il,jk", rho1b, rho2b, SAO, SAO, optimize=["einsum_path", (0, 2), (0, 1), (0, 1)]
                            )

                    # Final transformation of overlaps
                    for key in S:
                        S[key] = 1.0 - abs(S[key])
                    pairmax = max(S, key=S.get)
                    Omax = S[pairmax]
                    self.log.print(
                        f"             The best complement overlap: 1 - < {pairmax[0].symbol(Z=False)} | {pairmax[1].symbol(Z=False)} > = {Omax}"
                    )
                    expelled = False
                    for (s1, s2), O in S.items():
                        if O / Omax < job.tO:
                            expelled = True
                            self.log.print(
                                f"             Relative complement overlap 1 - < {s1.symbol(Z=False)} | {s2.symbol(Z=False)} > = {O} is too small."
                            )
                            pairs_to_expell[(f1, f2)].append((s1, s2))
                            if s1 in f1.aufbau_states and s2 in f2.aufbau_states:
                                self.log.print(
                                    "             Upper two site states are both aufbau site states, so some of aubau ESDs should be expelled! Aborting."
                                )
                                raise ValueError
                    if not expelled:
                        self.log.print("             No site-state pair need to be expelled!")
                    self.log.print("")

        # Remove ESDs containing at least one such site-state pair
        toremove = set()
        for ESD in ESDs:
            for (f1, f2), spairs in pairs_to_expell.items():
                for s1, s2 in spairs:
                    if ESD.site_states.get(f1) // s1 and ESD.site_states.get(f2) // s2:
                        toremove.add(ESD)
                        break
        ESDs = [ESD for ESD in ESDs if ESD not in toremove]
        self.log.print(f"       Number of aufbau and excited ESDs after overlap criterion: {len(ESDs)}")
        self.log.print("")
        return ESDs

    # ----END of ECI.overlap_criterion------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.spin_adapt------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def spin_adapt(self, m, allESDs):
        self.log.print(f"       Spin adaptation for multiplicity {m}:")
        ESDs = [ESD for ESD in allESDs if ESD.M == (m - 1)]
        self.log.print(f"          Found {len(ESDs)} ESDs with MS = {ESDs[0].M / 2}")

        def signature(esd):
            return tuple((state.Z, state.S, state.N) for state in esd.site_states.values())

        groups = {}
        for ESD in ESDs:
            sig = signature(ESD)
            groups.setdefault(sig, []).append(ESD)

        ECSFs = []
        # Target S(S+1) eigenvalue for multiplicity m
        for _, groupESDs in groups.items():
            S2mat = self.calculate_S2mat(groupESDs)
            S2val, groupU = np.linalg.eigh(S2mat, "U")
            mults = (np.sqrt(4.0 * abs(S2val)) + 1.0).astype(int)
            for i, mult in enumerate(mults):
                if mult == m:
                    ECSFs.append(excitonic_configuration_state_function(m, groupESDs, groupU[:, i]))
        if len(ECSFs) == 0:
            raise ValueError(
                f"          No ECSF that can be generated from given states and chosen ECI expansion corresponds to the requested multiplicity {m}"
            )

        ESDs = list({ESD for ECSF in ECSFs for ESD in ECSF.ESDs})
        ESD_index = {ESD: i for i, ESD in enumerate(ESDs)}
        self.log.print(f"          Constructed {len(ECSFs)} ECSFs spanned by {len(ESDs)} ESDs:")

        # Build big U
        U = np.zeros((len(ESDs), len(ECSFs)))
        for j, ECSF in enumerate(ECSFs):
            for i, ESD in enumerate(ECSF.ESDs):
                U[ESD_index[ESD], j] = ECSF.U[i]
            del ECSF.U

        return ESDs, ECSFs, U

    # ----END of ECI.spin_adapt------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.calculate_S2mat------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def calculate_S2mat(self, ESDs):
        nESD = len(ESDs)
        sites = list(ESDs[0].site_states.keys())
        n_sites = len(sites)

        # Site-invariant S/2
        S_by_2 = np.fromiter(
            (ESDs[0].site_states[f].S * 0.5 for f in sites),
            dtype=float,
            count=n_sites
        )

        # Preallocate containers
        # Object array for state references
        ESD_states = np.empty((nESD, n_sites), dtype=object)
        # Float array for M/2 values
        ESD_M = np.empty((nESD, n_sites), dtype=float)

        # Fill preallocated arrays
        for i, ESD in enumerate(ESDs):
            for k, f in enumerate(sites):
                st = ESD.site_states[f]
                ESD_states[i, k] = st
                ESD_M[i, k] = st.M * 0.5

        S2mat = np.zeros((nESD, nESD), dtype=float)

        # Diagonal terms
        S_term = np.sum(S_by_2 * (S_by_2 + 1.0))
        for i in range(nESD):
            M = ESD_M[i]
            S2mat[i, i] = S_term + (M.sum() ** 2 - np.dot(M, M))

        # Off-diagonal terms
        for i, j in itertools.combinations(range(nESD), 2):
            states_i = ESD_states[i]
            states_j = ESD_states[j]

            # Find differing sites (early exit)
            diffs = []
            for k in range(n_sites):
                if states_i[k] is not states_j[k]:
                    diffs.append(k)
                    if len(diffs) > 2:
                        break

            if len(diffs) != 2:
                continue

            f, g = diffs
            sf1, sg1 = states_i[f], states_i[g]
            sf2, sg2 = states_j[f], states_j[g]

            if sf1 // sf2 and sg1 // sg2:
                M1_f, M2_f = sf1.M, sf2.M
                M1_g, M2_g = sg1.M, sg2.M

                S_f, S_g = S_by_2[f], S_by_2[g]
                M_f = M1_f * 0.5
                M_g = M1_g * 0.5

                if M1_f == M2_f - 2 and M1_g == M2_g + 2:
                    x = S_f * (S_f + 1) - M_f * (M_f + 1)
                    y = S_g * (S_g + 1) - M_g * (M_g - 1)
                    S2mat[i, j] = math.sqrt(x * y)

                elif M1_f == M2_f + 2 and M1_g == M2_g - 2:
                    x = S_f * (S_f + 1) - M_f * (M_f - 1)
                    y = S_g * (S_g + 1) - M_g * (M_g + 1)
                    S2mat[i, j] = math.sqrt(x * y)

        return S2mat

    # ----END of ECI.calculate_S2mat------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

    # ----START of ECI.allocate------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
    def allocate(self):
        job = self.job
        for m in job.multiplicities:
            nESD = len(self.ECIbasis[m].ESDs)
            self.H[m] = np.zeros((nESD, nESD))
            self.J[m] = np.zeros((nESD, nESD))
            self.K[m] = np.zeros((nESD, nESD))
            self.S[m] = np.zeros((nESD, nESD))
            self.V1[m] = np.zeros((nESD, nESD))
            self.J1[m] = np.zeros((nESD, nESD))
            self.K1[m] = np.zeros((nESD, nESD))

